"""Writes doc/special-cases.md from the catalogue and the test cases: `python -m tests.gen_catalogue_doc` (`just catalogue`).

`test_catalogue_coverage.py` fails when the committed file is not what this renders, like a generated-code check.
"""

from __future__ import annotations

from pathlib import Path

from tests.catalogue import CATALOGUE, COVERED_BY_TESTS
from tests.testcases import CASES, REAL_FILES

DOC = Path(__file__).resolve().parent.parent / "doc" / "special-cases.md"

AREAS = {
    "file": "The file",
    "version": "Versions",
    "segment": "Segments",
    "index": "The raw data index",
    "layout": "The layout of the raw data",
    "type": "Data types",
    "prop": "Properties",
    "path": "Objects and paths",
    "scale": "Scaling",
    "daqmx": "Unsupported layouts",
    "robust": "Robustness",
}


def render() -> str:
    covered: dict[str, list[str]] = {identifier: [] for identifier in CATALOGUE}
    for case in CASES:
        for tag in case.tags:
            covered.setdefault(tag, []).append(f"`{case.id}`")
    real: dict[str, list[str]] = {}
    for name, tags in REAL_FILES.items():
        for tag in tags:
            real.setdefault(tag, []).append(f"`{name}`")

    lines = [
        "# Special cases of the TDMS format",
        "",
        "<!-- generated by `just catalogue` from tests/catalogue.py and tests/testcases.py: do not edit -->",
        "",
        (
            f"{len(CATALOGUE)} special cases, exercised by {len(CASES)} synthetic files (`tests/testcases.py`), "
            f"{len(REAL_FILES)} real files (`tests/data/real`) and a few behaviour tests."
        ),
        "",
    ]
    for area, title in AREAS.items():
        ids = [i for i in CATALOGUE if i.split(".")[0] == area]
        if not ids:
            continue
        lines += [f"## {title}", "", "| Case | The reader must | Exercised by |", "|---|---|---|"]
        for identifier in ids:
            by = covered[identifier] + [f"real: {r}" for r in real.get(identifier, [])]
            if identifier in COVERED_BY_TESTS:
                by.append(f"`{COVERED_BY_TESTS[identifier]}`")
            lines.append(f"| `{identifier}` | {CATALOGUE[identifier]} | {', '.join(by) or '**nothing**'} |")
        lines.append("")

    lines += ["## Real files", "", "| File | Special cases it exercises |", "|---|---|"]
    for name, tags in REAL_FILES.items():
        lines.append(f"| `{name}` | {', '.join(f'`{t}`' for t in tags)} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
